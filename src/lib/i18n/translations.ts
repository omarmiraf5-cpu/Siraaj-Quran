/** Makes a language's keyed text ready before it's shown (its phrases: loadPhrases). */
export async function loadTranslations(language: Language): Promise<void> {
  if (translations[language]) return;
  if (language === "so") translations.so = (await import("@/lib/i18n/translations.so")).SO;
  if (language === "ar") translations.ar = (await import("@/lib/i18n/translations.ar")).AR;
}
